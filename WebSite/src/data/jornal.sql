CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = auth.uid() AND perfil = 'admin' AND ativo = true AND deleted_at IS NULL
  );
$$;

DROP POLICY IF EXISTS "public reads published articles" ON public.articles;
CREATE POLICY "public reads published articles"
ON public.articles FOR SELECT
USING (status IN ('aprovado', 'publicado') AND deleted_at IS NULL);

DROP POLICY IF EXISTS "authenticated authors create articles" ON public.articles;
CREATE POLICY "authenticated authors create articles"
ON public.articles FOR INSERT TO authenticated
WITH CHECK (author_id = auth.uid());

DROP POLICY IF EXISTS "authors read own articles" ON public.articles;
CREATE POLICY "authors read own articles"
ON public.articles FOR SELECT TO authenticated
USING (author_id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS "admins manage articles" ON public.articles;
CREATE POLICY "admins manage articles"
ON public.articles FOR ALL TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "public reads active events" ON public.events;
CREATE POLICY "public reads active events"
ON public.events FOR SELECT
USING (status = 'publicado' AND deleted_at IS NULL);

DROP POLICY IF EXISTS "admins manage events" ON public.events;
CREATE POLICY "admins manage events"
ON public.events FOR ALL TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "anyone sends suggestions" ON public.suggestions;
CREATE POLICY "anyone sends suggestions"
ON public.suggestions FOR INSERT
WITH CHECK (true);

DROP POLICY IF EXISTS "admins manage suggestions" ON public.suggestions;
CREATE POLICY "admins manage suggestions"
ON public.suggestions FOR ALL TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

