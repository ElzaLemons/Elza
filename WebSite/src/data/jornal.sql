-- 3. TABELAS
CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  perfil public.user_profile NOT NULL DEFAULT 'estudante',
  matricula VARCHAR(50),
  serie VARCHAR(20),
  turma VARCHAR(20),
  telefone VARCHAR(30),
  ativo BOOLEAN NOT NULL DEFAULT true,
  ultimo_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.media_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  file_name VARCHAR(255) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  storage_path TEXT NOT NULL UNIQUE,
  public_url TEXT,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
  alt_text VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  autor_nome VARCHAR(150) NOT NULL,
  categoria VARCHAR(100) NOT NULL CHECK (categoria IN ('noticia_geral', 'artigo_cientifico', 'ser_onu', 'cultura_afro')),
  titulo VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE,
  resumo TEXT NOT NULL,
  conteudo TEXT NOT NULL,
  imagem_url TEXT,
  status public.article_status NOT NULL DEFAULT 'aguardando_coordenacao',
  motivo_recusa TEXT,
  featured BOOLEAN NOT NULL DEFAULT false,
  published_at TIMESTAMPTZ,
  published_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria VARCHAR(100),
  titulo VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE,
  descricao TEXT,
  data_inicio TIMESTAMPTZ NOT NULL,
  data_fim TIMESTAMPTZ,
  local VARCHAR(255) NOT NULL,
  imagem_id BIGINT REFERENCES public.media_files(id) ON DELETE SET NULL,
  inscricao_aberta BOOLEAN NOT NULL DEFAULT false,
  inscricao_url TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'publicado' CHECK (status IN ('rascunho', 'publicado', 'arquivado')),
  created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ,
  CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE TABLE IF NOT EXISTS public.suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anonimo BOOLEAN NOT NULL DEFAULT false,
  nome VARCHAR(150),
  email VARCHAR(255),
  perfil VARCHAR(50),
  categoria VARCHAR(100) NOT NULL DEFAULT 'outro',
  titulo VARCHAR(255) NOT NULL,
  mensagem TEXT NOT NULL,
  status public.suggestion_status NOT NULL DEFAULT 'recebido',
  responsavel_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  resposta TEXT,
  respondido_at TIMESTAMPTZ,
  ip_hash VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  acao VARCHAR(100) NOT NULL,
  entidade VARCHAR(100) NOT NULL,
  entidade_id BIGINT,
  dados_novos JSONB,
  ip_hash VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

